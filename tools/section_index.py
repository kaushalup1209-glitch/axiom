#!/usr/bin/env python3
"""Prints a Markdown index of every `===== SECTION: NAME =====` label in the app sources.

Usage (from the project root):
    python3 tools/section_index.py > docs/SECTION_INDEX.md

The index lets humans and AI assistants jump straight to a labelled block and confirms
that every section name is unique.
"""

# ===== SECTION: TOOL_SECTION_INDEX =====
import pathlib
import re
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_DIRS = [ROOT / "app" / "src", ROOT / "gradle", ROOT]
PATTERN = re.compile(r"=====\s*SECTION:\s*([A-Z0-9_]+)\s*=====")
EXTENSIONS = {".kt", ".kts", ".xml", ".toml", ".properties", ".pro"}


def collect():
    seen_files = set()
    entries = []
    for base in SOURCE_DIRS:
        candidates = base.rglob("*") if base != ROOT else base.glob("*")
        for path in sorted(candidates):
            if path.suffix not in EXTENSIONS or "build" in path.parts or path in seen_files:
                continue
            seen_files.add(path)
            for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
                match = PATTERN.search(line)
                if match and "END SECTION" not in line:
                    entries.append((match.group(1), path.relative_to(ROOT).as_posix(), line_number))
    return entries


def main():
    entries = collect()
    duplicates = [name for name, count in Counter(name for name, _, _ in entries).items() if count > 1]
    print("# Section index\n")
    print("Generated by `python3 tools/section_index.py`. Do not edit by hand.\n")
    print("| Section | File | Line |")
    print("|---|---|---|")
    for name, file, line in sorted(entries, key=lambda entry: (entry[1], entry[2])):
        print(f"| `{name}` | `{file}` | {line} |")
    if duplicates:
        print("\nDuplicate section names: " + ", ".join(sorted(duplicates)), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
# ===== END SECTION: TOOL_SECTION_INDEX =====
